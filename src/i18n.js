  function detect(preferred) {
    for (const tag of preferred || []) {
      const s = String(tag).toLowerCase();
      if (s.startsWith('zh')) return /hant|-tw|-hk|-mo/.test(s) ? 'zh-TW' : 'zh-CN';
      if (s.startsWith('ja')) return 'ja';
      if (s.startsWith('en')) return 'en';
    }
    return 'en';
  }

  let current = 'en';

